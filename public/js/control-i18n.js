/** Get translated text for a given key */
window.controlT = function controlT(key) {
  const lang = window._controlLang || 'en';
  return (window.ControlI18N[lang] || window.ControlI18N.en)[key]
      || window.ControlI18N.en[key]
      || key;
};

/** Apply i18n to all data-i18n elements + special elements */
window.applyControlLanguage = function applyControlLanguage(lang) {
  window._controlLang = lang || 'en';
  const d = window.ControlI18N[lang] || window.ControlI18N.en;

  // Page header
  const h1 = document.querySelector('.page-header h1');
  if (h1) h1.textContent = d.pageTitle;
  const sub = document.querySelector('.page-subtitle');
  if (sub) sub.textContent = d.pageSubtitle;

  // Header action links
  const headerLinks = document.querySelectorAll('.header-actions .ghost-button');
  const linkMap = [
    { href: '/display.html', key: 'openDisplay' },
    { href: '/starter', key: 'starterRemote' },
    { href: '/driver-overlay', key: 'driverOverlay' },
    { href: '/fastest', key: 'fastestOnly' },
    { href: '/entries.html', key: 'entriesEdit' },
    { href: '/results-overview.html', key: 'resultsOverview' },
    { href: '/settings.html', key: 'settings' },
  ];
  headerLinks.forEach(function (link) {
    var match = linkMap.find(function (m) { return link.getAttribute('href') === m.href; });
    if (match) link.textContent = d[match.key];
  });

  // All data-i18n attributes
  document.querySelectorAll('[data-i18n]').forEach(function (el) {
    if (d[el.dataset.i18n]) el.textContent = d[el.dataset.i18n];
  });

  // Status buttons
  document.querySelectorAll('[data-status]').forEach(function (btn) {
    var statusKey = 'status' + btn.dataset.status.charAt(0).toUpperCase() + btn.dataset.status.slice(1);
    if (d[statusKey]) btn.textContent = d[statusKey];
  });

  // Queue action buttons
  var queueBtnMap = {
    moveNextBtn: 'moveNextToNow',
    setNowBtn: 'setNow',
    setNextBtn: 'setNext',
    skipNextBtn: 'skipNext',
    unskipBtn: 'unskip',
    clearNowBtn: 'clearNow',
  };
  Object.keys(queueBtnMap).forEach(function (id) {
    var el = document.getElementById(id);
    if (el && d[queueBtnMap[id]]) el.textContent = d[queueBtnMap[id]];
  });

  // Anonymous mode badge
  var anonymousBadge = document.getElementById('anonymousModeBadge');
  if (anonymousBadge) anonymousBadge.textContent = d.anonymousModeBadge;

  // Search placeholder
  var searchInput = document.getElementById('entrySearch');
  if (searchInput) searchInput.placeholder = d.searchPlaceholder;

  // Run type buttons
  document.querySelectorAll('[data-run-type]').forEach(function (btn) {
    if (d[btn.dataset.runType]) btn.textContent = d[btn.dataset.runType];
  });

  // Run status options
  var runStatusSelect = document.getElementById('runStatus');
  if (runStatusSelect) {
    var statusOptionMap = {
      finished: 'statusFinishedOption',
      dq: 'statusDq',
      dnf: 'statusDnf',
      scratch: 'statusScratch',
      void: 'statusVoid',
    };
    runStatusSelect.querySelectorAll('option').forEach(function (opt) {
      var key = statusOptionMap[opt.value];
      if (key && d[key]) opt.textContent = d[key];
    });
  }

  // Action row buttons
  var actionBtnMap = {
    saveBtn: 'save',
    nextBtn: 'nextBtn',
    saveNextBtn: 'saveNext',
    resetBtn: 'reset',
    markInvalidBtn: 'markInvalid',
    createRerunBtn: 'createRerun',
  };
  Object.keys(actionBtnMap).forEach(function (id) {
    var el = document.getElementById(id);
    if (el && d[actionBtnMap[id]]) el.textContent = d[actionBtnMap[id]];
  });

  // Lock overlay buttons
  var lockRetryBtn = document.getElementById('controlLockRetryBtn');
  if (lockRetryBtn) lockRetryBtn.textContent = d.lockRetry;
  var lockForceBtn = document.getElementById('controlLockForceBtn');
  if (lockForceBtn) lockForceBtn.textContent = d.lockForce;
};
